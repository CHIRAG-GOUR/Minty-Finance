// Helper to generate sparkline and historical series
const genHistory = (base: number, volatility: number = 0.02) => {
  const points = 7;
  const arr: number[] = [];
  let curr = base * (1 - volatility * 3);
  for (let i = 0; i < points - 1; i++) {
    curr = curr * (1 + (Math.random() * volatility * 2 - volatility * 0.9));
    arr.push(Number(curr.toFixed(2)));
  }
  arr.push(base);
  return arr;
};

